import { useMemo, useState } from "react";
import { RefreshCw, Sparkles } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { templateSectionName, type CarePlanVersion, type ReviewSuggestion } from "@/lib/carePlansStore";
import { summariseApprovedPlan } from "@/lib/carePlanAssistant";

/** Summary of the approved plan and open review flags. Never changes the plan or its order. */
export default function PriorityRightNow({ personId, current, openSuggestions, canRegenerate, actor }: {
  personId: string; current: CarePlanVersion; openSuggestions: ReviewSuggestion[]; canRegenerate: boolean; actor: string;
}) {
  const [variant, setVariant] = useState(0);
  const [generated, setGenerated] = useState<{ by?: string; at: string }>(() => ({ at: new Date().toISOString() }));
  const points = useMemo(() => summariseApprovedPlan({
    approvedSections: current.sections.map((s) => ({ key: s.key, label: s.label ?? templateSectionName(personId, s.key), body: s.body })),
    openFlags: openSuggestions.map((s) => ({
      title: s.reason ?? "Care plan review suggested",
      overdue: !!s.dueAt && new Date(s.dueAt).getTime() < Date.now(),
    })),
    variant,
  }), [current, openSuggestions, variant, personId]);

  return (
    <div className="rounded-lg border border-primary/30 bg-primary/5 p-4" aria-label="Priority right now">
      <div className="flex flex-wrap items-center justify-between gap-2 mb-2">
        <div className="flex items-center gap-2 text-sm font-semibold"><Sparkles className="h-4 w-4 text-primary" /> Priority right now</div>
        <div className="flex items-center gap-2">
          <Badge variant="outline" className="text-[10px]">AI summary of approved plan</Badge>
          {canRegenerate && (
            <Button size="sm" variant="ghost" className="h-7 px-2 text-xs" onClick={() => { setVariant((v) => v + 1); setGenerated({ by: actor, at: new Date().toISOString() }); }}>
              <RefreshCw className="h-3.5 w-3.5 mr-1" /> Regenerate
            </Button>
          )}
        </div>
      </div>
      <ul className="list-disc pl-5 space-y-1 text-sm">
        {points.map((p, i) => <li key={i}>{p}</li>)}
      </ul>
      <div className="text-[11px] text-muted-foreground mt-2">
        From approved plan v{current.versionNumber} and open review flags only. A summary — it doesn&apos;t change the plan.
        {generated.by ? ` Regenerated by ${generated.by}.` : ""}
      </div>
    </div>
  );
}
